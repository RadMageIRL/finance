#!/usr/bin/env node
// The oracle fixtures must be reproducible: regenerate them with the independent Python
// decimal oracle (tests/oracle/generate.py, standard library only) and fail if any byte
// differs from the committed files. The generator itself exits non-zero if any published
// Regulation DD figure or identity check fails.

import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const DIR = join('tests', 'oracle', 'fixtures');

function hashes() {
  return Object.fromEntries(
    readdirSync(DIR)
      .filter((f) => f.endsWith('.json'))
      .sort()
      .map((f) => [f, createHash('sha256').update(readFileSync(join(DIR, f))).digest('hex')]),
  );
}

const before = hashes();
let run = null;
for (const python of ['python', 'python3']) {
  run = spawnSync(python, ['-I', join('tests', 'oracle', 'generate.py')], { encoding: 'utf8' });
  if (!run.error) break;
}
if (!run || run.error) {
  console.log('oracle check: Python 3 was not found (needed for the independent oracle)');
  process.exit(1);
}
if (run.status !== 0) {
  process.stdout.write(run.stdout ?? '');
  process.stdout.write(run.stderr ?? '');
  console.log('oracle check: the generator reported a failure');
  process.exit(1);
}
const after = hashes();
const changed = Object.keys({ ...before, ...after }).filter((f) => before[f] !== after[f]);
if (changed.length) {
  console.log(`oracle check: regenerated fixtures differ from the committed ones: ${changed.join(', ')}`);
  process.exit(1);
}
console.log(`oracle check: ${Object.keys(after).length} fixture files regenerated byte for byte`);
